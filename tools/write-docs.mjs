// Builds docs/FEATURES.md and docs/TUTORIAL.md from the JSON the screenshot runs produce.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const docs = path.join(root, 'docs');
const feat = JSON.parse(fs.readFileSync(path.join(docs, 'feature-check.json'), 'utf8'));
const tut = JSON.parse(fs.readFileSync(path.join(docs, 'tutorial', 'tutorial-run.json'), 'utf8'));

const section = (s, dir) => {
  let md = `### ${s.title || s.file}\n\n![${s.title || s.file}](${dir}/${s.file})\n\n${s.caption}\n`;
  if (s.marks.length) md += '\n' + s.marks.map((m, i) => `${i + 1}. ${m}`).join('\n') + '\n';
  return md + '\n';
};

// ---- FEATURES.md
let f = `# Feature guide\n\nEvery screenshot below was taken by an automated run that drives the real app in Chromium (see \`docs/feature-check.json\` for the pass/fail line of each check). Yellow numbers mark the controls described under each picture.\n\n`;
const ok = feat.checks.filter(c => c.ok).length;
f += `**Verification:** ${ok} of ${feat.checks.length} checks passed.\n\n<details><summary>Check list</summary>\n\n| Result | Check | Detail |\n| --- | --- | --- |\n` + feat.checks.map(c => `| ${c.ok ? 'PASS' : 'FAIL'} | ${c.name} | ${(c.detail || '').replace(/\|/g, '\\|')} |`).join('\n') + '\n\n</details>\n\n';
f += `## Contents\n\n` + feat.shots.map(s => `- [${s.title || s.file}](#${(s.title || s.file).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')})`).join('\n') + '\n\n';
for (const s of feat.shots) f += section(s, 'screenshots');
const extras = [
  ['17b-request-letter.png', 'Takedown request letter', 'The letter the request generator opens in a new window: indicators defanged, case number, TLP, analyst and date.'],
  ['23-case-brief.png', 'Case brief', 'The printable case brief: judgement, exhibits with stamps and grades, threads with their evidence, timeline, tasks and the board image. Save it as PDF from the print dialog.'],
  ['24-one-pager.png', 'Executive one-pager', 'The one-page version: judgement, confidence, what happened, next actions.'],
  ['26-board-export.png', 'Board exported as PNG', 'What "Export image" downloads: the whole board rendered to a high-resolution PNG with the case number and date.'],
].filter(([file]) => fs.existsSync(path.join(docs, 'screenshots', file)));
if (extras.length) { f += `## Generated documents\n\n`; for (const [file, title, cap] of extras) f += `### ${title}\n\n![${title}](screenshots/${file})\n\n${cap}\n\n`; }
fs.writeFileSync(path.join(docs, 'FEATURES.md'), f);

// ---- TUTORIAL.md
let t = fs.readFileSync(path.join(root, 'tools', 'tutorial-intro.md'), 'utf8') + '\n';
for (const s of tut.shots) t += section(s, 'tutorial');
const textras = [
  ['t13b-takedown-letter.png', 'The takedown letter', 'Generated by the request generator for the registrar abuse desk.'],
  ['t14-case-brief.png', 'The case brief', 'Printable brief for this case, as opened by "Case brief".'],
  ['t16-board-export.png', 'The board as exported', 'The PNG that "Export image" downloads for this case.'],
].filter(([file]) => fs.existsSync(path.join(docs, 'tutorial', file)));
if (textras.length) { t += `## Outputs\n\n`; for (const [file, title, cap] of textras) t += `### ${title}\n\n![${title}](tutorial/${file})\n\n${cap}\n\n`; }
t += fs.readFileSync(path.join(root, 'tools', 'tutorial-outro.md'), 'utf8');
fs.writeFileSync(path.join(docs, 'TUTORIAL.md'), t);
console.log('wrote docs/FEATURES.md and docs/TUTORIAL.md');
